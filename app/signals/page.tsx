function formatTime(val: any): string {
  if (!val) return "—";
  try {
    const date = typeof val === "object" && val?.toDate ? val.toDate() : new Date(val);
    if (isNaN(date.getTime())) return String(val);
    return date.toLocaleString("en-US", {
      month: "short",
      day: "numeric",
      hour: "2-digit",
      minute: "2-digit",
      second: "2-digit",
    });
  } catch {
    return String(val);
  }
}

